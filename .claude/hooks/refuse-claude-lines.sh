#!/usr/bin/env bash
# Runs before every shell command Claude Code makes (.claude/settings.json, PreToolUse on Bash).
#
# Louis, 2026-11-17, of "Co-Authored-By: Claude": "make a rule to take this out of commits and PR's". A skill's
# words only hold when the skill is loaded, so this holds the rule whether it is or not. It refuses two things:
# a commit made while the author is unset or is Claude, and a commit or a pull request whose text names Claude.
#
# Claude Code hands the command over as JSON on standard input, and the command's own text is in it, so plain
# matching on that text is enough. A refusal ends with code 2, and its message goes back to Claude to act on.
# What it can't see: a message or a body read from a file. /open-a-pull-request reads the body back for that.

input="$(cat)"

refuse() {
    echo "$1" >&2
    exit 2
}

# The repo is two folders up from this file, wherever the session was started from.
repo="$(cd "$(dirname "$0")/../.." && pwd)"

# A command that makes a commit: the author must be set, and not be Claude.
case "$input" in
    *"git commit"* | *"git merge"* | *"git pull"* | *"git cherry-pick"* | *"git revert"*)
        email="$(git -C "$repo" config user.email || true)"
        case "$email" in
            "" | *@anthropic.com)
                refuse "Refused: this would commit as '${email:-nobody}'. Every commit here is authored as Louis (/ship-it). Run: git config user.name \"Louis Marais\" && git config user.email \"84603591+bosbevk@users.noreply.github.com\", then run the command again."
                ;;
        esac
        ;;
esac

# The lines that name Claude, as a commit's trailer or a pull request's footer.
names_claude=false
case "$input" in
    *[Cc]"o-"[Aa]"uthored-"[Bb]"y: Claude"* | *"Claude-Session:"* | *"Generated with [Claude Code]"* | \
        *"Generated by [Claude Code]"* | *"claude.ai/code/session"*)
        names_claude=true
        ;;
esac
$names_claude || exit 0

# In a commit's message.
case "$input" in
    *"git commit"* | *"git merge"*)
        refuse "Refused: the commit message has a line that names Claude (a Co-Authored-By or Claude-Session trailer, or a 'Generated with Claude Code' line). Louis's rule is that no line names Claude (/ship-it). Take the line out and commit again."
        ;;
esac

# In a pull request's body, as it is opened or edited. A comment or a review is not a pull request's body.
case "$input" in
    *"/comments"* | *"/reviews"* | *"/replies"*)
        exit 0
        ;;
esac
case "$input" in
    *"/pulls"*"body="* | *"body="*"/pulls"* | *"gh pr create"* | *"gh pr edit"*)
        refuse "Refused: the pull request's body has a line that names Claude (a 'Generated with/by Claude Code' footer or a session link). Louis's rule is that no line names Claude (/open-a-pull-request). Take the line out and send it again. The 'Requested by Louis' lines of a project thread stay."
        ;;
esac

exit 0
